import PDFDocument from "pdfkit";

export type TicketJobCardData = {
  ticketNumber: string;
  statusLabel: string;
  createdAt: Date;
  updatedAt?: Date;
  description: string;
  residentName: string;
  flatNo?: string | null;
  tower?: string | null;
  phone?: string | null | undefined;
  categoryName: string;
  subcategoryName?: string | null;
  priorityLabel: string;
  complaintTypeLabel: string;
  assigneeName?: string | null;
  escalationLabel?: string | null;
  attachments?: Array<{ fileName: string }>;
  comments?: Array<{ authorName: string; body: string; createdAt: Date; isInternal?: boolean }>;
};

const NAVY = "#1e3a5f";
const ACCENT = "#2563eb";
const GREY = "#64748b";

function formatDate(date: Date) {
  return `${String(date.getDate()).padStart(2, "0")}-${String(date.getMonth() + 1).padStart(2, "0")}-${date.getFullYear()}`;
}

function formatTime(date: Date) {
  return date.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit", hour12: true });
}

function row(doc: PDFKit.PDFDocument, label: string, value: string, y: number, width: number) {
  doc.fillColor(GREY).font("Helvetica").fontSize(7).text(label.toUpperCase(), 40, y, { width: 130 });
  doc.fillColor("#0f172a").font("Helvetica-Bold").fontSize(10).text(value || "—", 175, y, { width });
}

export function generateTicketJobCardPdf(ticket: TicketJobCardData): Promise<Buffer> {
  return new Promise<Buffer>((resolve, reject) => {
    const chunks: Buffer[] = [];
    const doc = new PDFDocument({ margin: 0, size: "A4" });
    doc.on("data", (chunk) => chunks.push(Buffer.from(chunk)));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const pageWidth = 595;
    doc.rect(0, 0, pageWidth, 70).fill(NAVY);
    doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(17).text("OASIS VENETIA HEIGHTS", 40, 14, { width: pageWidth - 80 });
    doc.font("Helvetica").fontSize(10).fillColor("#cbd5e1").text("Help Desk · Job Card", 40, 37, { width: pageWidth - 80 });
    doc.fillColor(ACCENT).rect(40, 58, 110, 4).fill();

    doc.fillColor(NAVY).font("Helvetica-Bold").fontSize(13).text(`Complaint #${ticket.ticketNumber}`, 40, 92);
    doc.fillColor(GREY).font("Helvetica").fontSize(9).text(`Opened ${formatDate(ticket.createdAt)} at ${formatTime(ticket.createdAt)}`, 40, 110);

    let y = 140;
    row(doc, "Resident", ticket.residentName, y, 180); y += 26;
    row(doc, "Location", [ticket.tower, ticket.flatNo].filter(Boolean).join(" - "), y, 300); y += 26;
    if (ticket.phone) { row(doc, "Phone", ticket.phone, y, 200); y += 26; }
    row(doc, "Category", ticket.subcategoryName ? `${ticket.categoryName} · ${ticket.subcategoryName}` : ticket.categoryName, y, 300); y += 26;
    row(doc, "Priority", ticket.priorityLabel, y, 160); y += 26;
    row(doc, "Type", ticket.complaintTypeLabel, y, 160); y += 26;
    row(doc, "Assignee", ticket.assigneeName ?? "Not assigned", y, 300); y += 26;
    row(doc, "Escalation", ticket.escalationLabel ?? "Not escalated", y, 300); y += 26;
    row(doc, "Status", ticket.statusLabel, y, 200); y += 34;

    doc.fillColor(NAVY).font("Helvetica-Bold").fontSize(10).text("DESCRIPTION");
    doc.fillColor("#0f172a").font("Helvetica").fontSize(10).text(ticket.description, 40, doc.y, { width: 515, lineGap: 3 });
    doc.moveDown(1);

    if (ticket.attachments && ticket.attachments.length > 0) {
      doc.fillColor(NAVY).font("Helvetica-Bold").fontSize(10).text("ATTACHMENTS", 40);
      doc.moveDown(0.2);
      doc.fillColor("#0f172a").font("Helvetica").fontSize(9);
      for (const attachment of ticket.attachments) {
        doc.text(`• ${attachment.fileName}`, 40, doc.y, { width: 515 });
      }
      doc.moveDown(1);
    }

    const publicComments = (ticket.comments ?? []).filter((comment) => !comment.isInternal);
    if (publicComments.length > 0) {
      doc.fillColor(NAVY).font("Helvetica-Bold").fontSize(10).text("COMMENTS", 40);
      doc.moveDown(0.25);
      for (const comment of publicComments) {
        doc.fillColor("#0f172a").font("Helvetica-Bold").fontSize(8).text(`${comment.authorName} · ${formatDate(comment.createdAt)} ${formatTime(comment.createdAt)}`, 40, doc.y, { width: 515 });
        doc.fillColor("#334155").font("Helvetica").fontSize(9).text(comment.body, 40, doc.y, { width: 515, lineGap: 2 });
        doc.moveDown(0.4);
      }
    }

    doc.fillColor(GREY).font("Helvetica").fontSize(8).text("Generated by the Oasis Venetia Heights Help Desk. Verify job-card details with the assignee before carrying out the work.", 40, 780, { width: 515, align: "center" });
    doc.end();
  });
}
